def feasible(s: str, w: str, b: str, c: str) -> bool:
    if b == "refout" and (w != "none" or s == "ext"):
        return False                     # `ref` needs a variable; a receiver is never `ref`
    if s == "ext" and b != "params" and w in {"user_implicit", "closure", "method_group"}:
        # no user-defined conversion on a receiver; a lambda / method group has no receiver type
        return False
    return True


def handle_kind(c: str) -> str:
    return "param" if c.endswith("_param") else "local"


def param_type(w: str, b: str) -> str:
    if b == "refout":
        return HANDLE_TYPE.get(w, "MemoryStream")
    return PARAM_TYPE.get(w, "Stream")


def receiver_expr(w: str) -> str:
    e = EXPR[w]
    return e if w in BARE_RECEIVER or w == "parens" else f"({e})"


def call_statement(s: str, w: str, b: str) -> str:
    e = EXPR[w]
    if s == "inv":
        return {"pos": f"Sink({e}, true);", "named": f"Sink(leaveOpen: true, s: {e});",
                "params": f"SinkP({e});", "refout": "SinkRef(ref r);", "default": f"SinkD({e});"}[b]
    if s == "ctor":
        return {"pos": f"new Sink2({e}, true);", "named": f"new Sink2(leaveOpen: true, s: {e});",
                "params": f"new SinkP2({e});", "refout": "new SinkRef2(ref r);",
                "default": f"new SinkD2({e});"}[b]
    if s == "del":
        return {"pos": f"take({e}, true);", "named": f"take(leaveOpen: true, s: {e});",
                "params": f"takeP({e});", "refout": "takeRef(ref r);", "default": f"takeD({e});"}[b]
    r = receiver_expr(w)
    return {"pos": f"{r}.Ext(true);", "named": f"{r}.Ext(leaveOpen: true);",
            "params": f"Stream.Null.ExtP({e});", "default": f"{r}.ExtD();"}[b]


def callee_decl(s: str, w: str, b: str) -> list[str]:
    t = param_type(w, b)
    if s == "inv":
        return {"pos": [f"static void Sink({t} s, bool leaveOpen) {{ }}"],
                "named": [f"static void Sink({t} s, bool leaveOpen) {{ }}"],
                "params": [f"static void SinkP(params {t}[] xs) {{ }}"],
                "refout": [f"static void SinkRef(ref {t} s) {{ }}"],
                "default": [f"static void SinkD({t} s, bool leaveOpen = true) {{ }}"]}[b]
    if s == "ctor":
        return {"pos": [f"sealed class Sink2 {{ public Sink2({t} s, bool leaveOpen) {{ }} }}"],
                "named": [f"sealed class Sink2 {{ public Sink2({t} s, bool leaveOpen) {{ }} }}"],
                "params": [f"sealed class SinkP2 {{ public SinkP2(params {t}[] xs) {{ }} }}"],
                "refout": [f"sealed class SinkRef2 {{ public SinkRef2(ref {t} s) {{ }} }}"],
                "default": [f"sealed class SinkD2 {{ public SinkD2({t} s, bool leaveOpen = true) "
                            "{ } }"]}[b]
    if s == "del":
        return {"pos": [f"delegate void Take({t} s, bool leaveOpen);"],
                "named": [f"delegate void Take({t} s, bool leaveOpen);"],
                "params": [f"delegate void TakeP(params {t}[] xs);"],
                "refout": [f"delegate void TakeRef(ref {t} s);"],
                "default": [f"delegate void TakeD({t} s, bool leaveOpen = true);"]}[b]
    # Private extension methods: every case shares one compilation and the global namespace,
    # and an inaccessible extension method is not a candidate for another case's receiver.
    return {"pos": [f"static void Ext(this {t} s, bool leaveOpen) {{ }}"],
            "named": [f"static void Ext(this {t} s, bool leaveOpen) {{ }}"],
            "params": [f"static void ExtP(this Stream s, params {t}[] xs) {{ }}"],
            "default": [f"static void ExtD(this {t} s, bool leaveOpen = true) {{ }}"]}[b]


def delegate_param(b: str) -> str:
    return {"pos": "Take take", "named": "Take take", "params": "TakeP takeP",
            "refout": "TakeRef takeRef", "default": "TakeD takeD"}[b]


def helpers(w: str) -> list[str]:
    out: list[str] = []
    if w == "user_implicit":
        out.append(BOX)
    if w == "user_explicit":
        out.append(XBOX)
    if w == "boxing":
        out.append("struct Token : IDisposable { public void Dispose() { } }")
    if w == "nested":
        out.append("static Stream Wrap(Stream s) { return s; }")
    if w == "closure":
        out.append("static void Use(Stream s) { }")
    return out


def pairwise_case(s: str, w: str, b: str, c: str) -> tuple[str, str, dict[str, Any]]:
    """One generated program plus its designed classification."""
    name = f"pw-{s}-{w}-{b}-{c}".replace("_", "-")
    cls = "H_" + name.replace("-", "_")
    h = handle_kind(c)
    ht = HANDLE_TYPE.get(w, "MemoryStream")
    params: list[str] = []
    body: list[str] = []
    if h == "param":
        params.append(f"{ht} r")
    else:
        init = "new Token()" if ht == "Token" else "new MemoryStream()"
        body.append(f"{'var' if ht == 'MemoryStream' or ht == 'Token' else ht} r = {init};")
    if w in {"cond", "switch"}:
        if h == "param":
            params.append("MemoryStream q")
        else:
            body.append("var q = new MemoryStream();")
    if w == "cond":
        params.append("bool flag")
    if w == "switch":
        params.append("int k")
    if w == "coalesce":
        body.append("MemoryStream? p = null;")
    if s == "del":
        params.append(delegate_param(b))
    if c == "record_local":
        body.append("var keep = new MemoryStream();")
    call = call_statement(s, w, b)
    if c.startswith("unmodelled"):
        body.append(f"lock (Gate) {{ {call} }}")
    else:
        body.append(call)
    if c == "orphan_local":
        # Every candidate must escape for the orphan gate: the handle and, where a may-value
        # form declares one, its alternative.
        body.append("Field = r;")
        if w in {"cond", "switch"}:
            body.append("Field = q;")
    if c == "record_local":
        body.append("keep.Dispose();")

    members: list[str] = []
    members += callee_decl(s, w, b)
    members += helpers(w)
    if c.startswith("unmodelled"):
        members.append("static readonly object Gate = new object();")
    if c == "orphan_local":
        members.append("static object Field;")
    src = "\n".join([
        HEADER,
        f"// composition: site={s} value_flow={w} binding={b} carrier={c}",
        "using System;",
        "using System.IO;",
        "using System.Collections.Generic;",
        "",
        f"static class {cls}",
        "{",
        *[f"    {m}" for m in members],
        f"    static void M({', '.join(params)})",
        "    {",
        *[f"        {line}" for line in body],
        "    }",
        "}",
        "",
    ])

    # ---- the designed classification, from the frozen taxonomy ----
    occurrences: list[dict[str, Any]] = []
    site_kind = {"inv": "invocation", "ext": "invocation", "ctor": "object_creation",
                 "del": "delegate_invocation"}[s]
    ordinal = 1 if (s == "ext" and b == "params") else 0
    if w in EXCLUSION:
        occ: dict[str, Any] = {"symbol": "r", "verdict": "excluded", "explanation": EXCLUSION[w],
                               "site_kind": site_kind, "ordinal": ordinal}
        if w == "closure":
            occ["nested_function"] = True
        occurrences.append(occ)
        relevant = False
    else:
        if b in {"params", "refout"} or w in MAY_VALUE:
            expected = "opaque"
        else:
            expected = "param" if h == "param" else "var"
        if w == "nested":
            inner = {"symbol": "r", "verdict": "captured", "site_kind": "invocation", "ordinal": 0,
                     "expected": "param" if h == "param" else "var",
                     "enclosing": [] if (s == "ext" and b != "params") else ["nested_call_result"]}
            occurrences.append(inner)
        else:
            occurrences.append({"symbol": "r", "verdict": "captured", "site_kind": site_kind,
                                "ordinal": ordinal, "expected": expected})
            if w in {"cond", "switch"}:
                occurrences.append({"symbol": "q", "verdict": "captured", "site_kind": site_kind,
                                    "ordinal": ordinal, "expected": "opaque"})
        relevant = True
    if c == "orphan_local":
        occurrences.append(exc("r", "storage_assignment"))
        if w in {"cond", "switch"}:
            occurrences.append(exc("q", "storage_assignment"))
    if c == "record_local":
        occurrences.append({"symbol": "keep", "verdict": "excluded",
                            "explanation": "receiver_not_summary_parameter"})
    if c.startswith("record"):
        carrier = "functions"
    else:
        carrier = "guarded_functions" if relevant else "none"
    design = {
        "member": f"{cls}.M",
        "composition": {"site": s, "value_flow": w, "binding": b, "carrier": c},
        "carrier": carrier,
        "occurrences": occurrences,
        "red": {},
    }
    # F-PARAMS-ELEMENT (an expanded params element classified from its bare syntax) was pinned
    # RED here until A2.2-4R2 repaired it: the design above is the truth for every binding.
    return name, src, design


def pairwise(feasible_tuples: Sequence[tuple[str, ...]]) -> list[tuple[str, ...]]:
    """Greedy pairwise covering: deterministic (first best in enumeration order)."""
    def pairs(t: tuple[str, ...]) -> set[tuple[tuple[int, str], tuple[int, str]]]:
        return {((i, t[i]), (j, t[j])) for i, j in itertools.combinations(range(len(t)), 2)}
    uncovered: set[tuple[tuple[int, str], tuple[int, str]]] = set()
    for t in feasible_tuples:
        uncovered |= pairs(t)
    chosen: list[tuple[str, ...]] = []
    while uncovered:
        best, best_n = None, 0
        for t in feasible_tuples:
            n = len(pairs(t) & uncovered)
            if n > best_n:
                best, best_n = t, n
        if best is None:
            break
        chosen.append(best)
        uncovered -= pairs(best)
    return chosen


# ---- the named cases: compositions, shadowing, member kinds, vocabulary edges ----

PRELUDE = ["using System;", "using System.IO;", "using System.Collections.Generic;", ""]


def named_case(name: str, why: str, members: list[str], design: dict[str, Any],
               member_lines: list[str] | None = None) -> tuple[str, str, dict[str, Any]]:
    cls = "H_" + name.replace("-", "_")
    src = "\n".join([
        HEADER,
        f"// {why}",
        *PRELUDE,
        f"static class {cls}",
        "{",
        *[f"    {m}" for m in members],
        "}",
        "",
    ])
    design = {"member": f"{cls}.M", **design, "why": why}
    return name, src, design


def cap(symbol: str, kind: str = "invocation", ordinal: int = 0, expected: str = "var",
        **extra: Any) -> dict[str, Any]:
    return {"symbol": symbol, "verdict": "captured", "site_kind": kind, "ordinal": ordinal,
            "expected": expected, **extra}


def exc(symbol: str, name: str, **extra: Any) -> dict[str, Any]:
    return {"symbol": symbol, "verdict": "excluded", "explanation": name, **extra}


