#!/usr/bin/env python3
"""P-037 A2.2-4: the generated hostile census for the completeness oracle.

corpus/p037-hostile/cases/<case>.cs is one self-contained program per case and
corpus/p037-hostile/expected.json is the DESIGNED classification of every case:
which universe occurrence of the case's method must be captured (site kind,
declared ordinal, representation) or excluded (by which of the eleven frozen
names), which carrier production must deliver the record in, and, for a case
that witnesses a classified finding, exactly which RED the oracle must raise.
The design is written by this generator from the frozen taxonomy
(corpus/p037-relevance/registry.json, docs/notes/p037-formal-kernel.md §10.6),
never recorded from a run: the oracle is checked against it, so the oracle and
production cannot agree on nonsense.

Four factors are covered pairwise (every value of one factor meets every value
of every other at least once, under the feasibility constraints C# imposes):

  site form         inv (static invocation), ext (reduced extension receiver),
                    ctor (object creation), del (delegate invocation)
  value-flow        the 21 argument shapes of the relevance probe: the bare
                    handle, the transparent wrappers, the may-value forms, the
                    conversions, and every named exclusion's shape
  binding mode      positional, named and reordered, an expanded params slot,
                    ref, an omitted optional argument
  carrier admission the legacy pass's admission: a functions[] record through a
                    tracked local or an owned parameter, the guarded_functions[]
                    orphan carrier through an escaped local, and the unmodelled
                    construct gate (lock) for either handle kind

plus the named compositions the A2.2-4 GO asked for, the shadowing witnesses
(same spelling, different symbol), the member kinds the legacy pass does not
visit, and the argument shapes the frozen vocabulary has no name for.

Usage:
  p037_hostile_census.py generate      # (re)write the cases and expected.json
  p037_hostile_census.py check         # drift: the committed files equal a regeneration
"""

