def generate_all() -> tuple[dict[str, str], dict[str, Any]]:
    tuples = [t for t in itertools.product(SITES, WRAPPERS, BINDINGS, CARRIERS) if feasible(*t)]
    chosen = pairwise(tuples)
    sources: dict[str, str] = {}
    cases: dict[str, Any] = {}
    for t in chosen:
        name, src, design = pairwise_case(*t)
        sources[name] = src
        cases[name] = design
    for name, src, design in named_cases():
        sources[name] = src
        cases[name] = design
    factor_names = ["site", "value_flow", "binding", "carrier"]
    expected = {
        "schema": SCHEMA,
        "generator": "scripts/p037_hostile_census.py",
        "why": ("Designed classifications for the completeness oracle "
                "(frontend/roslyn/OwnSharp.Oracle): each case's method lists its universe "
                "occurrences with the verdict the frozen taxonomy assigns, the carrier "
                "production must deliver, and, for a case that witnesses a classified finding, "
                "the exact RED the oracle must raise. Written by the generator from the design, "
                "never recorded from a run."),
        "factors": {"site": SITES, "value_flow": WRAPPERS, "binding": BINDINGS,
                    "carrier": CARRIERS},
        "pairwise": {"feasible_tuples": len(tuples), "cases": len(chosen),
                     "factor_pairs": [f"{factor_names[a]} x {factor_names[b]}"
                                      for a, b in itertools.combinations(range(4), 2)]},
        "cases": dict(sorted(cases.items())),
    }
    return sources, expected


def write(sources: dict[str, str], expected: dict[str, Any], root: Path) -> None:
    cases = root / "cases"
    cases.mkdir(parents=True, exist_ok=True)
    for old in cases.glob("*.cs"):
        if old.stem not in sources:
            old.unlink()
    for name, src in sources.items():
        (cases / f"{name}.cs").write_text(src, encoding="utf-8")
    (root / "expected.json").write_text(json.dumps(expected, indent=1) + "\n", encoding="utf-8")


def check() -> int:
    sources, expected = generate_all()
    with tempfile.TemporaryDirectory(prefix="p037-hostile-") as td:
        write(sources, expected, Path(td))
        fresh = Path(td)
        problems: list[str] = []
        committed = {p.name for p in CASES.glob("*.cs")} if CASES.exists() else set()
        generated = {p.name for p in (fresh / "cases").glob("*.cs")}
        for n in sorted(committed - generated):
            problems.append(f"stale committed case {n}")
        for n in sorted(generated - committed):
            problems.append(f"missing committed case {n}")
        for n in sorted(generated & committed):
            if (CASES / n).read_bytes() != (fresh / "cases" / n).read_bytes():
                problems.append(f"case {n} differs from a regeneration")
        if not EXPECTED.exists() or EXPECTED.read_bytes() != (fresh / "expected.json").read_bytes():
            problems.append("expected.json differs from a regeneration")
    for p in problems:
        print(f"FAIL[hostile-census-drift]: {p}")
    if problems:
        return 1
    n_pairwise = expected["pairwise"]["cases"]
    print(f"ok[hostile-census-drift]: {len(sources)} case(s) equal a regeneration "
          f"({n_pairwise} pairwise + {len(sources) - n_pairwise} named)")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=("generate", "check"))
    args = ap.parse_args(argv)
